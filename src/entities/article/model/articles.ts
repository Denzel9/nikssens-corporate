export type AudienceFilter = "all" | Article["audience"][number];

export const matchesAudience = (
  article: Article,
  filter: AudienceFilter,
): boolean => {
  if (filter === "all") return true;
  return article.audience.includes(filter);
};

export const matchesArticleSearch = (article: Article, query: string): boolean => {
  const q = query.trim().toLowerCase();
  if (!q) return true;

  const inSections = article.sections.some(
    (section) =>
      section.title.toLowerCase().includes(q) ||
      section.paragraphs.some((p) => p.toLowerCase().includes(q)) ||
      section.bullets?.some((b) => b.toLowerCase().includes(q)),
  );

  return (
    article.title.toLowerCase().includes(q) ||
    article.description.toLowerCase().includes(q) ||
    article.navLabel.toLowerCase().includes(q) ||
    article.category.toLowerCase().includes(q) ||
    inSections
  );
};

export const filterArticles = (
  list: Article[],
  options: { query?: string; audience?: AudienceFilter },
): Article[] => {
  const audience = options.audience ?? "all";
  const query = options.query ?? "";

  return list.filter(
    (article) =>
      matchesAudience(article, audience) && matchesArticleSearch(article, query),
  );
};
