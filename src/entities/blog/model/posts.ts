export const getPostBySlug = (slug: string): BlogPost | undefined =>
  posts.find((post) => post.slug === slug);

export const getPostSlugs = (): string[] => posts.map((post) => post.slug);

export const getLatestPosts = (limit = 3): BlogPost[] =>
  [...posts]
    .sort((a, b) => (a.date < b.date ? 1 : -1))
    .slice(0, limit);
